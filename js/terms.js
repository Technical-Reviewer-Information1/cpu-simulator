  function def(term) { return DICT[term] || null; }

  /** ページ内の .term に説明を付ける */
  function attach(root) {
    (root || document).querySelectorAll('.term').forEach(el => {
      const t = el.dataset.t || el.textContent.trim();
      const d = DICT[t];
      if (!d) return;
      el.setAttribute('tabindex', '0');
      el.setAttribute('role', 'button');
      el.setAttribute('aria-label', t + ' の説明を表示');
      if (!el.querySelector('.term-pop')) {
        const pop = document.createElement('span');
        pop.className = 'term-pop';
        pop.innerHTML = '<b>' + t + '</b>' + d;
        el.appendChild(pop);
      }
      const toggle = e => {
        e.stopPropagation();
        const open = el.classList.contains('open');
        document.querySelectorAll('.term.open').forEach(x => x.classList.remove('open'));
        if (!open) el.classList.add('open');
      };
      el.addEventListener('click', toggle);
      el.addEventListener('keydown', e => { if (e.key === 'Enter' || e.key === ' ') { e.preventDefault(); toggle(e); } });
    });
    document.addEventListener('click', () => document.querySelectorAll('.term.open').forEach(x => x.classList.remove('open')));
  }

  /** 用語集セクションを作る */
  function glossary(container, terms) {
    if (!container) return;
    const list = terms.filter(t => DICT[t]);
    container.innerHTML = '<dl class="gloss">' + list.map(t =>
      '<dt>' + t + '</dt><dd>' + DICT[t] + '</dd>').join('') + '</dl>';
  }

  global.Terms = { def, attach, glossary, DICT };
  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', () => attach());
  else attach();
